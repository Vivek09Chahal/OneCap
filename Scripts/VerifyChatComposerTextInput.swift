// Run with:
// swiftc -parse-as-library -swift-version 6 OneCap/Views/Chat/ChatComposerTextInput.swift \
//   Scripts/VerifyChatComposerTextInput.swift -o /tmp/VerifyChatComposerTextInput
import AppKit
import SwiftUI
import UniformTypeIdentifiers

@main
struct VerifyChatComposerTextInput {
    @MainActor
    private final class State {
        var text = ""
        var selection: TextSelection?
        var textWrites = 0
        var selectionWrites = 0
        var focused = false
        var droppedFiles: [URL] = []
    }

    @MainActor
    static func main() async {
        _ = NSApplication.shared
        let state = State()
        let input = ChatComposerTextInput(
            text: Binding(get: { state.text }, set: { state.text = $0; state.textWrites += 1 }),
            selection: Binding(get: { state.selection }, set: { state.selection = $0; state.selectionWrites += 1 }),
            font: .systemFont(ofSize: 16), textColor: .textColor,
            placeholderColor: .placeholderTextColor, tint: .controlAccentColor,
            dropFiles: { urls in
                MainActor.assertIsolated()
                state.droppedFiles.append(contentsOf: urls)
            }, pasteImage: { _ in }, submit: {},
            moveSelection: { _ in false }, escape: { false },
            focusChanged: { state.focused = $0 })
        let coordinator = input.makeCoordinator()
        let editor = NSTextView()
        let notification = Notification(name: NSText.didChangeNotification, object: editor)

        // Native notifications may arrive inside a SwiftUI layout pass.
        // Neither binding should be written on that call stack.
        editor.string = "Hello"
        editor.setSelectedRange(NSRange(location: 5, length: 0))
        coordinator.textDidChange(notification)
        editor.string = "Hello 👋🏽"
        editor.setSelectedRange(NSRange(location: editor.string.utf16.count, length: 0))
        coordinator.textDidChange(notification)
        coordinator.textViewDidChangeSelection(notification)
        precondition(state.textWrites == 0 && state.selectionWrites == 0)
        precondition(!coordinator.shouldApplyBoundState, "Layout must preserve pending typing")
        await drainMainQueue()
        precondition(state.text == editor.string && state.textWrites == 1)
        precondition(state.selectionWrites == 1)
        precondition(state.selection?.indices == .selection(state.text.endIndex..<state.text.endIndex))

        // Moving the caret publishes selection without rewriting the draft.
        editor.setSelectedRange(NSRange(location: 0, length: 5))
        coordinator.textViewDidChangeSelection(notification)
        precondition(state.selectionWrites == 1)
        await drainMainQueue()
        precondition(state.textWrites == 1 && state.selectionWrites == 2)
        precondition(state.selection?.indices == .selection(state.text.startIndex..<state.text.index(state.text.startIndex, offsetBy: 5)))

        // A newer draft supplied by SwiftUI wins over pending native edits.
        editor.string = "Pending edit"
        coordinator.textDidChange(notification)
        state.text = "Different chat"
        state.selection = nil
        precondition(coordinator.shouldApplyBoundState)
        await drainMainQueue()
        precondition(state.text == "Different chat" && state.selection == nil)

        // Suppress callbacks generated by updateNSView itself.
        coordinator.isUpdatingView = true
        coordinator.textDidChange(notification)
        coordinator.textViewDidChangeSelection(notification)
        coordinator.isUpdatingView = false
        await drainMainQueue()
        precondition(state.textWrites == 1 && state.selectionWrites == 2)

        // AppKit delivers promised files on an operation queue, not the main actor.
        // Calling the production callback there must not trigger an isolation trap.
        let promisedURL = URL(fileURLWithPath: "/tmp/OneCap-promised-screenshot.png")
        let completion = coordinator.filePromiseCompletion()
        let promiseQueue = OperationQueue()
        await withCheckedContinuation { continuation in
            promiseQueue.addOperation {
                precondition(!Thread.isMainThread)
                completion(promisedURL, nil)
                continuation.resume()
            }
        }
        await drainMainQueue()
        precondition(state.droppedFiles == [promisedURL])

        // Failed promises must not import a file.
        await Task.detached {
            completion(promisedURL, NSError(domain: NSCocoaErrorDomain, code: NSFileReadUnknownError))
        }.value
        await drainMainQueue()
        precondition(state.droppedFiles == [promisedURL])

        // The whole composer also accepts unsaved images without a file URL.
        let screenshot = NSItemProvider()
        screenshot.suggestedName = "Screenshot.png"
        let pixels = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 2, pixelsHigh: 2,
            bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
            colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
        let png = pixels.representation(using: .png, properties: [:])!
        screenshot.registerDataRepresentation(forTypeIdentifier: UTType.png.identifier, visibility: .all) { completion in
            completion(png, nil)
            return nil
        }
        let screenshotURLs = await ComposerDroppedFiles.load([screenshot])
        precondition(screenshotURLs.count == 1, "An unsaved screenshot must become an attachment")
        precondition(try! Data(contentsOf: screenshotURLs[0]) == png)
        precondition(screenshotURLs[0].lastPathComponent == "Screenshot.png")
        try? FileManager.default.removeItem(at: screenshotURLs[0].deletingLastPathComponent())

        // Existing files keep their original URL; unrelated text remains text.
        let fileProvider = NSItemProvider(contentsOf: promisedURL) ?? NSItemProvider()
        fileProvider.registerDataRepresentation(forTypeIdentifier: UTType.fileURL.identifier, visibility: .all) { completion in
            completion(promisedURL.dataRepresentation, nil)
            return nil
        }
        let fileURLs = await ComposerDroppedFiles.load([fileProvider])
        precondition(fileURLs == [promisedURL])
        let textURLs = await ComposerDroppedFiles.load([NSItemProvider(object: "plain text" as NSString)])
        precondition(textURLs.isEmpty)

        // Dismantled views cannot publish queued text, selection, or focus.
        editor.string = "Removed editor"
        coordinator.textDidChange(notification)
        coordinator.focusChanged(true)
        precondition(!state.focused)
        let scroll = NSScrollView()
        scroll.documentView = editor
        ChatComposerTextInput.dismantleNSView(scroll, coordinator: coordinator)
        await Task.detached { completion(promisedURL, nil) }.value
        await drainMainQueue()
        precondition(state.droppedFiles == [promisedURL], "Dismantled editors must ignore promised files")
        precondition(state.text == "Different chat" && !state.focused)
        precondition(state.textWrites == 1 && state.selectionWrites == 2)
        print("Verified deferred bindings, coalesced Unicode edits, caret changes, newer drafts, update guards, background file promises, failed promises, and teardown.")
    }

    @MainActor
    private static func drainMainQueue() async {
        await withCheckedContinuation { continuation in
            DispatchQueue.main.async { continuation.resume() }
        }
    }
}
